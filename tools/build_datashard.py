def hp(body, will):
    return 10 + 5 * ((int(body) + int(will)) // 2)


def rec(**kw):
    b, w = kw["body"], kw["will"]
    kw.setdefault("hp", hp(b, w))
    kw.setdefault("init", kw["ref"])
    kw.setdefault("humanity", max(10, kw["emp"] * 10 - kw.get("hum_cost", 0)))
    kw.pop("hum_cost", None)
    return kw


