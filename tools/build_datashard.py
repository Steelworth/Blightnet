def role_entries():
    out = []
    for role, spec in ROLES.items():
        slug = role.lower()
        for tier, st in spec["stats"].items():
            sk = TIER_SKILL[tier]
            skills = spec["skills"].format(**sk)
            out.append(
                rec(
                    id=f"{slug}-{tier}",
                    name=f"{role} · {tier.title()}",
                    role=role,
                    rank=st["rank"],
                    kind=spec["kind"],
                    tier=tier,
                    rep=TIER_REP[tier],
                    int=st["int"],
                    ref=st["ref"],
                    dex=st["dex"],
                    tech=st["tech"],
                    cool=st["cool"],
                    will=st["will"],
                    luck=st["luck"],
                    move=st["move"],
                    body=st["body"],
                    emp=st["emp"],
                    sp=st["sp"],
                    weapons=[{"n": n, "d": d} for n, d in spec["weps"]],
                    skills=skills,
                    chrome=spec["chrome"],
                    gear=spec["gear"],
                    blurb=spec["blurbs"][tier],
                    traits=[{"n": spec["trait"][0] + f" {st['rank']}", "d": spec["trait"][1]}],
                    look=spec["look"],
                    hum_cost=TIER_HUM[tier],
                )
            )
    return out


